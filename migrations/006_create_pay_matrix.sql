-- Based on 7th Pay Commission Pay Matrix

CREATE TABLE IF NOT EXISTS pay_matrix (
    id SERIAL PRIMARY KEY,
    stage VARCHAR(5) NOT NULL,
    level INTEGER NOT NULL,
    basic_pay INTEGER NOT NULL,
    CONSTRAINT uq_pay_matrix_stage_level UNIQUE (stage, level),
    CONSTRAINT chk_pay_matrix_level_range CHECK (level >= 1 AND level <= 40),
    CONSTRAINT chk_pay_matrix_basic_pay_positive CHECK (basic_pay > 0)
);

CREATE INDEX IF NOT EXISTS idx_pay_matrix_stage ON pay_matrix(stage);
CREATE INDEX IF NOT EXISTS idx_pay_matrix_stage_level ON pay_matrix(stage, level);

